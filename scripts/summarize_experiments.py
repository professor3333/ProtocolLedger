"""Build the dev experiment table from committed reports (seeds aggregated).

    uv run python scripts/summarize_experiments.py

Reads reports/baselines/*-dev.json and reports/neural/*-dev.json and writes
reports/experiments-dev.md. Configurations run with several seeds are shown as
mean ± sample standard deviation; single runs show their bootstrap 95% CI.
"""

from __future__ import annotations

import json
import re
import statistics
from collections import defaultdict
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
BASELINES = {"rules-dev.json": "Rules", "crf-logreg-dev.json": "CRF + logistic regression"}
DESCRIPTIONS = {
    "scibert-lr2e-5": "SciBERT, lr 2e-5, hard negatives",
    "scibert-lr5e-5": "SciBERT, lr 5e-5, hard negatives",
    "bert-lr2e-5": "BERT-base-cased (control), lr 2e-5",
    "bert-lr5e-5": "BERT-base-cased (control), lr 5e-5",
    "scibert-frozen": "SciBERT, frozen encoder (heads only)",
    "scibert-uniform-negatives": "SciBERT, lr 2e-5, uniform negatives",
    "scibert-no-structure": "SciBERT, lr 2e-5, no type / distance features",
}


def metrics(report: dict[str, Any]) -> dict[str, Any]:
    e, g = report["end_to_end"], report["gold_entities"]
    return {
        "entity": e["entities"]["micro"]["f1"],
        "relation": e["relations"]["micro"]["f1"],
        "relation_ci": e["relations"]["micro"]["f1_ci95"],
        "gold": g["relations"]["micro"]["f1"],
        "attach": e["quantity_attachment"]["accuracy"],
    }


def fmt(values: list[float], ci: list[float] | None = None) -> str:
    if len(values) > 1:
        return f"{statistics.mean(values):.3f} ± {statistics.stdev(values):.3f}"
    if ci:
        return f"{values[0]:.3f} [{ci[0]:.3f}, {ci[1]:.3f}]"
    return f"{values[0]:.3f}"


def main() -> int:
    rows = []
    for name, label in BASELINES.items():
        m = metrics(json.loads((ROOT / "reports" / "baselines" / name).read_text()))
        rows.append(
            (
                label,
                "—",
                m["entity"],
                fmt([m["relation"]], m["relation_ci"]),
                m["gold"],
                m["attach"],
            )
        )
    groups: dict[str, list[dict[str, Any]]] = defaultdict(list)
    seeds: dict[str, list[str]] = defaultdict(list)
    for path in sorted((ROOT / "reports" / "neural").glob("*-dev.json")):
        report = json.loads(path.read_text())
        match = re.match(r"(.+)-s(\d+)$", report["run"])
        if not match or "smoke" in report["run"]:
            continue
        groups[match[1]].append(metrics(report))
        seeds[match[1]].append(match[2])
    for key in DESCRIPTIONS:
        if key not in groups:
            continue
        ms = groups[key]
        ci = ms[0]["relation_ci"] if len(ms) == 1 else None
        rows.append(
            (
                DESCRIPTIONS[key],
                ", ".join(sorted(seeds[key], key=int)),
                statistics.mean(m["entity"] for m in ms),
                fmt([m["relation"] for m in ms], ci),
                statistics.mean(m["gold"] for m in ms),
                statistics.mean(m["attach"] for m in ms),
            )
        )
    lines = [
        "# Dev experiments",
        "",
        "Generated by `scripts/summarize_experiments.py` from committed reports. All numbers "
        "are on the **dev** split; the locked test split has not been evaluated.",
        "",
        "| System | Seeds | Entity F1 | **Relation F1, end-to-end** | Relation F1, gold entities "
        "| Quantity attachment |",
        "|---|---|---:|---:|---:|---:|",
    ]
    for label, seed, ent, rel, gold, att in rows:
        lines.append(f"| {label} | {seed} | {ent:.3f} | {rel} | {gold:.3f} | {att:.3f} |")
    lines += [
        "",
        "Several seeds: mean ± sample standard deviation. One seed: bootstrap 95% CI "
        "over documents.",
        "",
    ]
    (ROOT / "reports" / "experiments-dev.md").write_text("\n".join(lines), "utf-8")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
